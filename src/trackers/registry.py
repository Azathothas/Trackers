#: Sources whose entries may be counted toward the published dataset.
PUBLISHABLE_ROLES: frozenset[Role] = frozenset({Role.PRIMARY, Role.DERIVATIVE})

#: Sources that may be compared for unique contribution (T-101).
COMPARABLE_ROLES: frozenset[Role] = frozenset({Role.PRIMARY})


def by_id(source_id: str) -> Source:
    for s in SOURCES:
        if s.id == source_id:
            return s
    raise KeyError(f"no such source: {source_id!r}")


def enabled_sources() -> tuple[Source, ...]:
    return tuple(s for s in SOURCES if s.enabled)
