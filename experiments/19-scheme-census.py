#!/usr/bin/env python3
"""
QUESTION
    Which URL schemes and which reachability networks actually occur across
    every tracker source this project might consume -- and is RULES 3.1's
    protocol table a complete and correctly-factored description of them?

WHY IT EXISTS
    RULES 3.1 says, of its own protocol table: "Do not assume this table
    is complete -- it is one sample of one README." TODO/RULES.md C-21 makes the
    same point more sharply: the tracker COUNTS in a README move daily and are
    not load-bearing, but the SCHEME SET is load-bearing, because the domain
    model and the health-state machine are built on it.

    the definition of done (HISTORY/gates.md) requires a test that "protocol classification covers every
    scheme found by the census (experiment 19)". This is experiment 19. Its
    output is the authority that test is written against.

THE FINDING THAT MOTIVATED THE TWO-AXIS MODEL
    RULES 3.1 tabulates `udp://`, `http://`, `https://`, `ws://`/`wss://`,
    `*.i2p`, "yggdrasil hosts" and `*.onion` as if they were seven values of
    one variable. They are not. Measured against ngosang/trackerslist at commit
    1e61597e0160027add8bbc36e7161796454d6f3a:

        trackers_all_i2p.txt        schemes present: http, udp
        trackers_all_yggdrasil.txt  schemes present: http
        trackers_all_ws.txt         schemes present: wss   (not ws)

    An I2P tracker is not a URL with an `i2p://` scheme. It is an ORDINARY
    `http://` or `udp://` URL whose HOSTNAME ends in `.i2p`, and which is
    unreachable without an I2P router. Yggdrasil is the same shape with an
    IPv6 literal inside 0200::/7 instead of a suffix.

    So a classifier keyed on scheme alone gets I2P and Yggdrasil wrong in the
    most damaging possible direction: it sees `http://` and sends them to the
    ordinary HTTP prober, which fails, and the tracker is recorded dead. That
    is exactly the correctness bug RULES 3.1 requirement 1 forbids.

    This experiment therefore reports TWO axes and their cross-product:

        transport   how you speak to it        udp / http / https / ws / wss
        network     where it lives, hence      clearnet / i2p / yggdrasil /
                    whether we can reach it    onion / unknown

INPUTS (pinned)
    Sources are pinned in SOURCES below by URL. Where a source is a git
    repository the pinned commit is recorded in the results file, because a
    census against a moving branch measures a different thing every day.

    --offline reads only from --cache-dir, so the census is reproducible with
    no network and so CI can run it without touching anyone's server.

EXIT CODES
    0  the measurement ran
    1  the measurement ran and an --expect assertion failed
    2  the measurement could not run

USAGE
    ./19-scheme-census.py                       # fetch, census, write cache
    ./19-scheme-census.py --offline             # re-run from cache, no network
    ./19-scheme-census.py --expect-known-schemes  # regression check
"""

from __future__ import annotations

