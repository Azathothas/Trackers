import ipaddress
import json
import os
import re
import sys
import urllib.error
import urllib.request
from collections import Counter, defaultdict
from urllib.parse import urlsplit

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import _conditions as C  # noqa: E402

USER_AGENT = (
    "trackers/0.1 "
    "(+https://github.com/Azathothas/Trackers; "
    "tracker list census; contact via repository issues)"
)

# --- pinned sources -----------------------------------------------------------
# Every source HISTORY/reference-sweep.md names, plus the per-protocol lists that are the
# only place ws/i2p/yggdrasil entries appear at all.
#
# `role` matters and is not decoration. A DERIVATIVE source is one that is
# generated by concatenating other sources in this table. Including a
# derivative in a unique-contribution calculation is a methodology error: it
# makes every one of its own inputs look redundant, because of course they
# appear in their own downstream copy.
#
# Measured, not assumed: pkgforge_all is a strict superset of desirefire_all
# (1091 of 1091 entries), and it also carries 91 of ngosang_all's 99 and 52 of
# newtrackon_stable's 53. It is the concatenation those three feed. The first
# version of this experiment did not model that and reported desirefire as
# contributing 0 unique trackers, which is an artefact, not a finding.
#
# `blacklist` is a third role: it is a list of trackers deliberately EXCLUDED
# by an upstream. Its entries must never be counted as available trackers, but
# the reasons attached to them are evidence (RULES 4) and it is censused
# so that the reasons can be read.
SOURCES: list[tuple[str, str, str]] = [
    ("ngosang_all", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all.txt", "primary"),
    ("ngosang_best", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_best.txt", "derivative"),
    ("ngosang_udp", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_udp.txt", "derivative"),
    ("ngosang_http", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_http.txt", "derivative"),
    ("ngosang_https", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_https.txt", "derivative"),
    ("ngosang_ws", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_ws.txt", "primary"),
    ("ngosang_i2p", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_i2p.txt", "primary"),
    ("ngosang_yggdrasil", "https://raw.githubusercontent.com/ngosang/trackerslist/master/trackers_all_yggdrasil.txt", "primary"),
    ("ngosang_blacklist", "https://raw.githubusercontent.com/ngosang/trackerslist/master/blacklist.txt", "blacklist"),
    ("newtrackon_all", "https://newtrackon.com/api/all", "primary"),
    ("newtrackon_live", "https://newtrackon.com/api/live", "derivative"),
    ("newtrackon_stable", "https://newtrackon.com/api/stable", "derivative"),
    ("xiu2_all", "https://raw.githubusercontent.com/XIU2/TrackersListCollection/master/all.txt", "primary"),
    ("xiu2_best", "https://raw.githubusercontent.com/XIU2/TrackersListCollection/master/best.txt", "derivative"),
    ("desirefire_all", "https://raw.githubusercontent.com/DeSireFire/animeTrackerList/master/AT_all.txt", "primary"),
    ("pkgforge_all", "https://raw.githubusercontent.com/pkgforge-security/Trackers/main/trackers_all.txt", "derivative"),
]

# A scheme this project has a prober for, or a documented reason it has none.
KNOWN_TRANSPORTS = {"udp", "http", "https", "ws", "wss"}
KNOWN_NETWORKS = {"clearnet", "i2p", "yggdrasil", "onion"}

# Yggdrasil uses the 0200::/7 IPv6 range. Recorded here as the single place the
# constant lives, with its source, so it is checkable rather than folklore.
YGGDRASIL_NET = ipaddress.ip_network("0200::/7")  # yggdrasil-network.github.io


def classify_network(host: str) -> str:
    """Which network does this hostname live on, hence can we reach it at all?

    This is deliberately independent of the URL scheme -- see the module
    docstring. Getting this wrong marks an unreachable-by-design tracker dead.
    """
    h = host.strip("[]").lower().rstrip(".")
    if h.endswith(".i2p"):
        return "i2p"
    if h.endswith(".onion"):
        return "onion"
    try:
        ip = ipaddress.ip_address(h)
    except ValueError:
        return "clearnet"
    if ip.version == 6 and ip in YGGDRASIL_NET:
        return "yggdrasil"
    return "clearnet"


def parse_entries(text: str) -> tuple[list[str], dict]:
    """Pull tracker URLs out of a source body. Reports what it rejected.

    Upstream bodies are untrusted (RULES 5): this only ever reads and
    counts. It never executes, never resolves, and never writes a path derived
    from source content.
    """
    stats = Counter()
    urls = []
    for raw in text.splitlines():
        line = raw.strip()
        if not line:
            stats["blank"] += 1
            continue
        # ngosang's blacklist.txt carries a trailing ` # reason` comment. Split
        # it off rather than rejecting the line, because the reasons are
        # evidence (see the sweep write-up) and the URL is still a URL.
        if "#" in line:
            line = line.split("#", 1)[0].strip()
            stats["had_comment"] += 1
            if not line:
                stats["comment_only"] += 1
                continue
        if "://" not in line:
            stats["no_scheme"] += 1
            continue
        urls.append(line)
        stats["url"] += 1
    return urls, dict(stats)


def census(urls: list[str]) -> dict:
    transports, networks, cross, bad = Counter(), Counter(), Counter(), []
    for u in urls:
        try:
            p = urlsplit(u)
            scheme = (p.scheme or "").lower()
            host = p.hostname or ""
        except ValueError as e:
            bad.append({"url": u[:200], "error": f"{type(e).__name__}: {e}"})
            continue
        if not scheme or not host:
            bad.append({"url": u[:200], "error": "no scheme or no host"})
            continue
        net = classify_network(host)
        transports[scheme] += 1
        networks[net] += 1
        cross[f"{scheme}|{net}"] += 1
    return {
        "transports": dict(sorted(transports.items())),
        "networks": dict(sorted(networks.items())),
        "transport_x_network": dict(sorted(cross.items())),
        "unparseable": bad,
    }


def fetch(url: str, cache_dir: str, offline: bool, timeout: float) -> tuple[str | None, dict]:
    safe = re.sub(r"[^A-Za-z0-9._-]", "_", url)[:150]
    path = os.path.join(cache_dir, safe)
    if offline:
        if not os.path.exists(path):
            return None, {"from": "cache", "ok": False, "detail": "not cached"}
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.read(), {"from": "cache", "ok": True}
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            # Bounded read: RULES 5.2 requires every network operation to
            # have a bounded response size. 32 MiB is far above any real list
            # and far below anything that could exhaust a runner.
            body = r.read(32 * 1024 * 1024).decode("utf-8", "replace")
            status, ctype = r.status, r.headers.get("Content-Type", C.UNKNOWN)
    except urllib.error.HTTPError as e:
        return None, {"from": "network", "ok": False, "detail": f"HTTP {e.code}"}
    except Exception as e:
        return None, {"from": "network", "ok": False, "detail": f"{type(e).__name__}: {e}"}
    os.makedirs(cache_dir, exist_ok=True)
    # An explicit newline: a cached upstream body is compared byte for byte
    # against the live one, and a cache written with the platform separator
    # would differ from every fetch on Windows. RULES 15.5.
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    return body, {"from": "network", "ok": True, "http_status": status,
                  "content_type": ctype, "bytes": len(body)}


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--cache-dir", default=os.path.join(here, "fixtures", "source-cache"))
    ap.add_argument("--offline", action="store_true", help="read only from cache")
    ap.add_argument("--timeout", type=float, default=30.0)
    ap.add_argument("--expect-known-schemes", action="store_true",
                    help="exit 1 if a transport or network appears that this "
                         "project has no documented handling for")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    per_source, all_urls = {}, []
    union: set[str] = set()
    by_source_urls: dict[str, set[str]] = {}

    roles = {name: role for name, _u, role in SOURCES}
    for name, url, role in SOURCES:
        body, meta = fetch(url, args.cache_dir, args.offline, args.timeout)
        if body is None:
            per_source[name] = {"url": url, "role": role, "fetch": meta,
                                "entries": None, "census": None, "parse_stats": None}
            continue
        # An HTML body where a list was expected is a source failure, not zero
        # trackers (RULES 3.10 invariant). Detect and say so.
        looks_html = body.lstrip()[:200].lower().startswith(("<!doctype", "<html"))
        urls, pstats = parse_entries(body)
        per_source[name] = {
            "url": url,
            "role": role,
            "fetch": meta,
            "looks_like_html": looks_html,
            "entries": len(urls),
            "parse_stats": pstats,
            "census": census(urls),
        }
        by_source_urls[name] = set(urls)
        all_urls.extend(urls)
        if role != "blacklist":
            union |= set(urls)

    overall = census(sorted(union))

    # Unique contribution, computed among PRIMARY sources only.
    #
    # Comparing a primary against a derivative that contains it answers no
    # question anyone has. The blacklist is excluded for a different reason:
    # its entries are trackers an upstream deliberately removed, so counting
    # them as a "contribution" would invert their meaning.
    primaries = {n: u for n, u in by_source_urls.items() if roles.get(n) == "primary"}
    unique_contribution = {}
    for name, s_urls in primaries.items():
        others = set().union(*[v for k, v in primaries.items() if k != name]) if len(primaries) > 1 else set()
        unique_contribution[name] = {
            "total": len(s_urls),
            "unique_among_primaries": len(s_urls - others),
        }

    # Derivatives are reported separately: what matters about a derivative is
    # whether it carries anything its own inputs do not, which would mean it
    # has a source nobody has identified.
    primary_union = set().union(*primaries.values()) if primaries else set()
    derivative_report = {}
    for name, s_urls in by_source_urls.items():
        if roles.get(name) != "derivative":
            continue
        derivative_report[name] = {
            "total": len(s_urls),
            "not_in_any_primary": len(s_urls - primary_union),
        }

    unknown_transports = sorted(set(overall["transports"]) - KNOWN_TRANSPORTS)
    unknown_networks = sorted(set(overall["networks"]) - KNOWN_NETWORKS)

    results = {
        "per_source": per_source,
        "union": {
            "distinct_urls": len(union),
            **overall,
        },
        "unique_contribution_primaries_only": unique_contribution,
        "derivative_orphans": derivative_report,
        "source_roles": roles,
        "unknown_transports": unknown_transports,
        "unknown_networks": unknown_networks,
        "sources_failed": [n for n, s in per_source.items() if s["entries"] is None],
    }

    conditions = C.collect(sample_counts={
        "sources_configured": len(SOURCES),
        "sources_fetched": sum(1 for s in per_source.values() if s["entries"] is not None),
        "distinct_urls": len(union),
    }, extra={
        "offline": args.offline,
        "cache_dir": os.path.relpath(args.cache_dir, here),
        "user_agent": USER_AGENT,
        "yggdrasil_range": str(YGGDRASIL_NET),
    })

    out = args.out or C.results_path(__file__)
    C.emit("Which URL schemes and reachability networks actually occur across "
           "every tracker source this project might consume?",
           conditions, results, out)

    print("\nPER SOURCE")
    for name, s in per_source.items():
        if s["entries"] is None:
            print(f"  {name:22s} FETCH FAILED  {s['fetch'].get('detail')}")
            continue
        html = "  <== HTML, not a list!" if s["looks_like_html"] else ""
        t = ",".join(f"{k}={v}" for k, v in s["census"]["transports"].items())
        n = ",".join(f"{k}={v}" for k, v in s["census"]["networks"].items())
        print(f"  {name:22s} {s['entries']:5d} entries  [{t}]  [{n}]{html}")

    u = results["union"]
    print(f"\nUNION  {u['distinct_urls']} distinct URLs across "
          f"{len(SOURCES) - len(results['sources_failed'])} sources")
    print(f"  transports : {u['transports']}")
    print(f"  networks   : {u['networks']}")
    print("  transport x network:")
    for k, v in u["transport_x_network"].items():
        print(f"      {k:22s} {v}")

    print("\nUNIQUE CONTRIBUTION among PRIMARY sources")
    print("  (derivatives excluded: a source cannot be redundant with its own copy)")
    for name, d in sorted(unique_contribution.items(),
                          key=lambda kv: -kv[1]["unique_among_primaries"]):
        print(f"  {name:22s} {d['unique_among_primaries']:5d} unique of {d['total']:5d}")

    print("\nDERIVATIVES (entries not present in ANY primary => an unidentified source)")
    for name, d in sorted(derivative_report.items(),
                          key=lambda kv: -kv[1]["not_in_any_primary"]):
        print(f"  {name:22s} {d['not_in_any_primary']:5d} orphan of {d['total']:5d}")

    print("\nCOVERAGE CHECK")
    print(f"  transports with no documented handling: {unknown_transports or 'none'}")
    print(f"  networks with no documented handling  : {unknown_networks or 'none'}")
    if u["unparseable"]:
        print(f"  unparseable entries: {len(u['unparseable'])} (first 3 shown)")
        for b in u["unparseable"][:3]:
            print(f"      {b}")

    print("\nWHAT THIS DOES NOT ESTABLISH")
    print("  - That any of these trackers is alive. This counts strings; it")
    print("    performs no probe of any kind.")
    print("  - That the scheme set is stable. It is one census on one day, and")
    print("    it is the reason --expect-known-schemes exists as a regression")
    print("    check rather than a one-off reading.")
    print("  - THE NETWORK OF A HOSTNAME-ADDRESSED YGGDRASIL TRACKER. Measured")
    print("    limitation: ngosang's single yggdrasil entry is")
    print("    http://yggtracker.i2p.rocks:80/announce -- an ordinary hostname,")
    print("    which this URL-only classifier necessarily reports as clearnet.")
    print("    Only the _ip variant exposes the 0200::/7 literals that identify")
    print("    the network. So `networks` UNDER-counts yggdrasil, and correct")
    print("    classification requires DNS resolution -- a time-varying")
    print("    inference (the three dedup questions in src/trackers/dedup.py point 3), not a property of the URL. The")
    print("    health checker owns that step; a census must not pretend to it.")

    if args.expect_known_schemes and (unknown_transports or unknown_networks):
        print("\nEXPECTATION FAILED: --expect-known-schemes")
        print("  A scheme or network appeared that this project does not "
              "document handling for. Classify it before publishing anything "
              "that claims to cover it.")
        return C.EXIT_MEASURED_AND_FAILED
    return C.EXIT_MEASURED


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        sys.exit(C.EXIT_COULD_NOT_RUN)
